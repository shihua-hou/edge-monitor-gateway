#ifndef __ADC_LIGHT_H
#define __ADC_LIGHT_H

#include "stm32f1xx_hal.h"
#include "types.h"

/* 光敏电阻（战舰板 PA1 = ADC1_CH1）
 * 光越强 → 光敏电阻越小 → 分压点电压越高 → 百分比越大 */
/* 返回 0=成功。失败不再 while(1) 死等——这几个函数是在最高优先级的采集
   任务里调用的，卡住等于整机停摆，看门狗复位后又卡在同一行，变成无限
   重启循环。外设坏了就标记为不可用，系统带着残疾继续跑，由上层如实上报 */
u8   ADC_Light_Init(void);
/* 0=成功，光照百分比 0~100 写进 *percent；非 0=读取失败，*percent 不被修改
   （调用方应保留上一次的值并把光敏标记为故障，而不是当成 0 用） */
u8   ADC_Light_GetPercent(u8 *percent);

/* 电池电压（PC5 = ADC1_CH15，经模块板载 100k/10k 分压）。
 * 返回 0=成功；1=读取失败；**2=电压低到不可能，判定为没接线**。
 * 2 和 1 必须分开："那根线没接"和"电池没电了"在大屏上是完全不同的两件事，
 * 把前者报成后者就是假告警——而假告警看多了，真告警也就没人信了。 */
u8   ADC_Battery_GetMv(u16 *mv);

#endif
